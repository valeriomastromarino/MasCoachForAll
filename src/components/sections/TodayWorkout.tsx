"use client";

// "Allenamento di oggi": the workout the engine picks from the Intervals.icu library (lib/training/suggest.ts), with
// the reasons, the alternatives and a week plan. Nothing is written to Intervals.icu until a button says so.
import { useId, useMemo, useState, useSyncExternalStore } from "react";
import { IconChevronDown, IconPlayerPlayFilled } from "@tabler/icons-react";
import { onTrainer } from "@/lib/calendar";
import type { DashboardData } from "@/lib/dashboard";
import { loadProfile, PROFILE_EVENT, profileSnapshot } from "@/lib/profile/profile";
import { PHASE_INFO, planFromToday, weekFor } from "@/lib/training/season";
import { loadSeason, SEASON_EVENT, seasonSnapshot } from "@/lib/training/seasonStore";
import { recentFromRides } from "@/lib/training/done";
import { choicesOf } from "@/lib/training/weeks";
import { classifyWorkout, fuelFor, type Place, plannedFits, planWeek, type Proposal, suggestWorkout, type SuggestInput, type Suggestion, toleratedCarbs } from "@/lib/training/suggest";
import Link from "next/link";
import { addDays } from "@/lib/dates";
import { fmt, fmtDuration } from "../format";
import { Description, WorkoutProfile, send } from "../calendar/shared";
import { refreshPlanned, useLibrary, useLife, useOverrides, usePlanned } from "../data/trainingData";

const subscribe = (cb: () => void) => {
  window.addEventListener(PROFILE_EVENT, cb);
  return () => window.removeEventListener(PROFILE_EVENT, cb);
};

const PLACES: [Place, string][] = [
  ["any", "Indifferente"],
  ["outdoor", "Fuori"],
  ["indoor", "Rulli"],
];

const KIND_NAME = { carico: "di carico", scarico: "leggera", taper: "di tapering", gara: "della gara", stop: "di stop" };
const DAY_NAMES = ["Lun", "Mar", "Mer", "Gio", "Ven", "Sab", "Dom"];
const dayName = (date: string) => `${DAY_NAMES[(new Date(`${date}T12:00:00`).getDay() + 6) % 7]} ${Number(date.slice(8))}`;

const subscribeSeason = (cb: () => void) => {
  window.addEventListener(SEASON_EVENT, cb);
  return () => window.removeEventListener(SEASON_EVENT, cb);
};

/** The workout text as Intervals.icu steps, without the library's credit line. */
const steps = (text: string) =>
  text
    .split("\n")
    .filter((l) => !/^generated by/i.test(l.trim()))
    .join("\n")
    .trim();

// Phone app, design D «Azione» with the rules of A (19 November 2026): the workout in large type, its numbers on one line,
// the profile, then the one thing to do («Pedala ora» or «Programma su Intervals»); steps, food and reasons under «Dettagli».

/** The text buttons under the workout: each one a full 44 px target. */
const ROW_BUTTON = "inline-flex min-h-11 items-center gap-1 rounded-full px-3 text-sm font-semibold";

/** Carbohydrates for the numbers line: «30-60 g/h di carboidrati», or «solo acqua». */
function carbsShort(mins: number, cls: Parameters<typeof fuelFor>[0]["cls"], cap: number | null): string {
  const c = fuelFor({ mins, cls }, cap).carbs;
  return c.startsWith("0 ") ? "solo acqua" : `${c} di carboidrati`;
}

/** Today's session on the trainer starts from here, like the round «Pedala» of the bar. */
function PedalaOra({ id }: { id: string }) {
  return (
    <Link
      href={`/rulli/${encodeURIComponent(id)}`}
      className="mt-4 flex min-h-14 w-full items-center justify-center gap-2 rounded-[18px] text-[17px] font-semibold"
      style={{ background: "var(--brand)", color: "var(--on-brand)" }}
    >
      <IconPlayerPlayFilled size={22} aria-hidden />
      Pedala ora
    </Link>
  );
}

function DetailsToggle({ open, onToggle, controls }: { open: boolean; onToggle: () => void; controls: string }) {
  return (
    <button type="button" onClick={onToggle} aria-expanded={open} aria-controls={controls} className={ROW_BUTTON} style={{ color: "var(--accent-ink)" }}>
      Dettagli
      <IconChevronDown size={16} aria-hidden className="transition-transform" style={{ transform: open ? "rotate(180deg)" : undefined }} />
    </button>
  );
}

/** Food and drink for the workout: carbohydrates (never above what the athlete tolerates, `cap` g/h), water and what to eat before. */
function Fuel({ mins, cls, cap }: { mins: number; cls: Parameters<typeof fuelFor>[0]["cls"]; cap: number | null }) {
  const f = fuelFor({ mins, cls }, cap);
  return (
    <div className="mt-3" aria-label="Alimentazione">
      <div className="grid grid-cols-2 gap-2">
        <div className="rounded-xl px-3 py-2" style={{ background: "var(--background)" }}>
          <div className="num text-sm font-medium">{f.carbs}</div>
          <div className="text-[11px] text-muted">carboidrati</div>
        </div>
        <div className="rounded-xl px-3 py-2" style={{ background: "var(--background)" }}>
          <div className="num text-sm font-medium">{f.water}</div>
          <div className="text-[11px] text-muted">acqua</div>
        </div>
      </div>
      <div className="mt-1.5 text-[11px] text-muted">
        Prima: {f.before}.{f.cappedAt !== null && ` Carboidrati fermi a ${f.cappedAt} g/h, quanto tolleri ora.`} Indicazione, non un dato registrato.
      </div>
    </div>
  );
}

/** compact (phone app): only the workout and its button, without the phase text, the reasons and the week proposal; tap it to open the steps. */
export function TodayWorkout({ data, compact = false }: { data: DashboardData; compact?: boolean }) {
  const raw = useSyncExternalStore(subscribe, profileSnapshot, () => "");
  const rawSeason = useSyncExternalStore(subscribeSeason, seasonSnapshot, () => "");
  const life = useLife(data.today);
  const overrides = useOverrides(data.today);
  const season = useMemo(() => {
    const setup = rawSeason ? loadSeason() : null;
    return setup ? planFromToday(setup, data.today, data.status.ctl, life) : null;
  }, [rawSeason, data.today, data.status.ctl, life]);
  const stored = useMemo(() => (raw ? loadProfile() : null), [raw]);
  // Days fixed in the Stagione page.
  const fixedDays = useMemo(() => choicesOf(rawSeason ? loadSeason() : null), [rawSeason]);
  const carbCap = toleratedCarbs(stored?.profile?.carboTollerati);
  const library = useLibrary();
  const [placeChoice, setPlaceChoice] = useState<Place>("any");
  const [chosen, setChosen] = useState(0);
  const [showOther, setShowOther] = useState(false);
  /** Phone app: «Dettagli» opens the steps, food and drink, and the reasons. */
  const [open, setOpen] = useState(false);
  const detailsId = useId();
  const [saving, setSaving] = useState<string>("");
  const [done, setDone] = useState<Record<string, boolean>>({});
  const [error, setError] = useState<string | null>(null);

  const today = data.today;
  const planned = usePlanned(today, data.athlete.ftp);
  // What the athlete said in the chat (a place, a time limit, a feeling) counts here too.
  const place: Place = placeChoice !== "any" ? placeChoice : (overrides.place ?? "any");
  const setPlace = setPlaceChoice;

  const input: SuggestInput | null = useMemo(() => {
    if (!library) return null;
    return {
      // What is already on the Intervals.icu calendar: the week is laid out around it.
      planned: (planned ?? []).map((w) => ({ date: w.date, workout: { ...w, id: 0 } })),
      chosen: fixedDays,
      date: today,
      readiness: data.status.readiness.level,
      tsbYesterday: data.status.tsbYesterday,
      ctl: data.status.ctl,
      recent: recentFromRides(data.activities, library),
      library,
      profile: stored?.profile,
      phenotype: stored?.phenotype ?? null,
      place,
      ftp: data.athlete.ftp,
      indoorFtp: data.athlete.indoorFtp,
      season,
      rampRate: data.status.rampRate,
      life,
      gym: data.gymDays,
      feeling: overrides.feeling ?? null,
      override: { maxMins: overrides.maxMins, easier: overrides.easier, wantClass: overrides.wantClass, restToday: overrides.restToday },
    };
  }, [library, today, data, stored, place, season, life, overrides, planned, fixedDays]);

  const suggestion: Suggestion | null = useMemo(() => (input ? suggestWorkout(input) : null), [input]);
  const week = useMemo(() => (input && planned ? planWeek(input, planned.map((w) => ({ date: w.date, workout: { ...w, id: 0 } }))) : []), [input, planned]);
  const todayPlanned = planned?.find((w) => w.date === today) ?? null;
  // Nothing today: show the next workout already on the calendar ("Domani", or the day).
  const nextPlanned = planned?.filter((w) => w.date > today).sort((a, b) => a.date.localeCompare(b.date))[0] ?? null;
  const shownPlanned = todayPlanned ?? (suggestion?.kind === "rest" ? nextPlanned : null);
  const whenLabel = shownPlanned && shownPlanned.date !== today ? (shownPlanned.date === addDays(today, 1) ? "Domani" : dayName(shownPlanned.date)) : null;
  const weekPlan = weekFor(season, today);
  // A workout already on the calendar is checked against today: readiness, illness or injury, yesterday's form and work.
  // The athlete programs weeks ahead, so without this the card showed a VO2max session on a red day as if nothing was wrong.
  const unfit = useMemo(() => {
    if (!input || !todayPlanned) return null;
    const fit = plannedFits(input, { ...todayPlanned, id: 0 });
    return fit.ok ? null : fit.why;
  }, [input, todayPlanned]);

  /** `replace` = the workout on the calendar that this one takes the place of: it is removed first. */
  const schedule = async (p: Proposal, date: string, replace?: string) => {
    const key = `${date}:${p.workout.id}`;
    setSaving(key);
    setError(null);
    let err = replace ? await send(`/api/calendar/events/${encodeURIComponent(replace)}`, "DELETE") : null;
    // A session for the trainer is written as an indoor one, so Intervals.icu uses the indoor FTP for its watts.
    if (!err) err = await send("/api/calendar/events", "POST", { workoutId: p.workout.id, date, indoor: p.indoor });
    setSaving("");
    if (err) setError(err);
    else {
      setDone((d) => ({ ...d, [key]: true }));
      // Read the calendar again: today's card turns into the session in programme (with «Pedala ora» if it is for the
      // trainer), and the round «Pedala» of the bar opens it. Until 19 November 2026 only a replacement was read again.
      refreshPlanned();
      if (replace) setShowOther(false);
    }
  };

  if (data.source === "demo") return null;

  // A bike ride already done today replaces the plan: show what was actually ridden.
  const ride =
    data.activities
      .filter((a) => a.date.slice(0, 10) === today && a.movingTime > 0 && ["strada", "offroad", "rulli"].includes(a.category))
      .sort((a, b) => b.movingTime - a.movingTime)[0] ?? null;

  // The card shows the engine's proposal (not a session already in programme, not a rest day).
  const proposing = !ride && suggestion !== null && planned !== null && !(shownPlanned && !showOther) && suggestion.kind !== "rest";
  // Phone app: the place matters only for a proposal, so the chips show only then.
  const header = (
    <div className="flex flex-wrap items-center justify-between gap-2">
      <h2 className="text-sm font-medium">Allenamento di oggi</h2>
      {!ride && (!compact || proposing) && <div className="flex gap-1" role="group" aria-label="Dove ti alleni oggi">
        {PLACES.filter(([p]) => !compact || p !== "any").map(([p, label]) => (
          <button
            key={p}
            type="button"
            aria-pressed={place === p}
            onClick={() => (setPlace(compact && place === p ? "any" : p), setChosen(0))}
            className={compact ? "min-h-11 rounded-full px-4 text-sm" : "rounded-full px-3 py-1 text-xs"}
            style={{ background: place === p ? "var(--accent-bg)" : "transparent", color: place === p ? "var(--accent-ink)" : "var(--muted)", border: `1px solid ${place === p ? "var(--accent-ink)" : "var(--border)"}` }}
          >
            {label}
          </button>
        ))}
      </div>}
    </div>
  );
  /** Phone app: a text link becomes a 44 px target. */
  const tap = compact ? " inline-flex min-h-11 items-center" : "";

  let body: React.ReactNode;
  if (ride) {
    const pill = "num rounded-full px-2.5 py-0.5 text-xs";
    body = (
      <Link href={`/attivita/${ride.id}`} className="mt-3 block rounded-2xl p-3 active:scale-[0.99]" style={{ background: "var(--background)", border: "1px solid var(--border)" }}>
        <div className="flex items-center gap-2">
          <span className="rounded-full px-2 py-0.5 text-[11px]" style={{ background: "var(--good-bg)", color: "var(--good-ink)" }}>
            Fatto oggi
          </span>
          <span className="text-[11px] text-faint">{ride.indoor ? "rulli" : "fuori"}</span>
        </div>
        <div className="mt-1 text-base font-medium">{ride.name}</div>
        <div className="mt-2 flex flex-wrap gap-1.5">
          <span className={pill} style={{ background: "var(--neutral-bg)" }}>{fmtDuration(ride.movingTime)}</span>
          {ride.distanceKm !== null && ride.distanceKm > 0 && <span className={pill} style={{ background: "var(--neutral-bg)" }}>{fmt(ride.distanceKm, 0)} km</span>}
          {ride.tss !== null && <span className={pill} style={{ background: "var(--accent-bg)", color: "var(--accent-ink)" }}>{fmt(ride.tss)} TSS</span>}
          {ride.np !== null && <span className={pill} style={{ background: "var(--neutral-bg)" }}>NP {fmt(ride.np, 0)} W</span>}
          {ride.IF !== null && <span className={pill} style={{ background: "var(--neutral-bg)" }}>IF {fmt(ride.IF, 2)}</span>}
          {ride.avgHr !== null && <span className={pill} style={{ background: "var(--neutral-bg)" }}>{fmt(ride.avgHr, 0)} bpm</span>}
        </div>
        <div className="mt-2 text-[11px] text-faint">Tocca per aprire il dettaglio</div>
      </Link>
    );
  } else if (!suggestion || planned === null) {
    body = <p className="mt-3 text-sm text-muted">Scelgo dalla tua libreria…</p>;
  } else if (shownPlanned && !showOther) {
    const w = shownPlanned;
    const cls = classifyWorkout({ ...w, id: 0 }).cls;
    const mins = w.secs ? Math.round(w.secs / 60) : null;
    const trainer = onTrainer(w);
    // Today's session on the trainer, right for today: it starts from the card. A session the day does not suit keeps
    // «Vedi cosa fare oggi» as the main action (the round «Pedala» of the bar still opens it).
    const pedala = compact && !whenLabel && !unfit && trainer && w.blocks.length > 0;
    body = (
      <div className="mt-3">
        <div className="text-xs text-muted">{whenLabel ? "Oggi niente in programma" : "Hai già in programma su Intervals"}</div>
        {whenLabel && (
          <span className="mt-1.5 inline-block rounded-full px-2 py-0.5 text-[11px]" style={{ background: "var(--accent-bg)", color: "var(--accent-ink)" }}>
            {whenLabel}
          </span>
        )}
        {unfit && !whenLabel && (
          <div className="mt-2 rounded-xl px-3 py-2 text-xs" role="alert" style={{ background: "var(--warning-bg)", color: "var(--warning-ink)" }}>
            <div className="font-medium">Oggi non è il giorno giusto per questa seduta</div>
            <div className="mt-0.5">{unfit}</div>
            <button type="button" onClick={() => setShowOther(true)} className={`mt-2 rounded-full font-medium ${compact ? "min-h-11 px-4 text-sm" : "px-3 py-1 text-xs"}`} style={{ background: "var(--warning-ink)", color: "var(--warning-bg)" }}>
              Vedi cosa fare oggi
            </button>
          </div>
        )}
        {compact ? (
          <>
            <div className="mt-1 text-[22px] font-semibold leading-tight tracking-tight">{w.name}</div>
            <div className="num mt-0.5 text-sm text-muted">
              {[mins !== null ? `${mins} min${trainer ? " sui rulli" : ""}` : null, w.tss ? `TSS ${Math.round(w.tss)}` : null, mins !== null ? carbsShort(mins, cls, carbCap) : null].filter(Boolean).join(" · ")}
            </div>
          </>
        ) : (
          <>
            <div className="mt-1 font-medium">{w.name}</div>
            <div className="num text-xs text-muted">
              {mins !== null ? `${mins} min` : ""}
              {w.tss ? ` · TSS ${Math.round(w.tss)}` : ""}
            </div>
          </>
        )}
        {w.blocks.length > 0 && (
          <div className="mt-3">
            <WorkoutProfile blocks={w.blocks} height={compact ? 64 : 44} axis={false} scrub={compact} />
          </div>
        )}
        {pedala && <PedalaOra id={w.id} />}
        {compact ? (
          <>
            <div className="mt-2 flex flex-wrap justify-center gap-2">
              <DetailsToggle open={open} onToggle={() => setOpen((o) => !o)} controls={detailsId} />
              {/* A race is not swapped for a workout (and Intervals.icu would not let the app remove it); another day's session changes in Piano. */}
              {!w.race && !whenLabel && (
                <button type="button" onClick={() => setShowOther(true)} className={ROW_BUTTON} style={{ color: "var(--accent-ink)" }} aria-label="Cambia: proponimi un'altra seduta">
                  Cambia
                </button>
              )}
            </div>
            <div id={detailsId} hidden={!open}>
              {w.description && (
                <div className="mt-2">
                  <Description text={steps(w.description)} />
                </div>
              )}
              {mins !== null && <Fuel mins={mins} cls={cls} cap={carbCap} />}
            </div>
          </>
        ) : (
          <>
            {mins !== null && <Fuel mins={mins} cls={cls} cap={carbCap} />}
            {!w.race && (
              <button type="button" onClick={() => setShowOther(true)} className="mt-3 text-xs text-faint underline">
                Proponimi un&apos;altra cosa
              </button>
            )}
          </>
        )}
      </div>
    );
  } else if (suggestion.kind === "rest") {
    body = (
      <div className="mt-3">
        <p className="text-sm">{suggestion.reason}</p>
        {/* Back to the session shown before «Proponimi un'altra cosa» (also when it was the next day's one). */}
        {showOther && shownPlanned && (
          <button type="button" onClick={() => setShowOther(false)} className={`mt-3 text-xs text-faint underline${tap}`}>
            Torna a quello in programma: {shownPlanned.name}
          </button>
        )}
      </div>
    );
  } else {
    const options = [suggestion.main, ...suggestion.alternatives];
    const p = options[Math.min(chosen, options.length - 1)];
    const key = `${today}:${p.workout.id}`;
    body = (
      <div className="mt-3">
        <div className="flex items-center gap-2">
          <span className="rounded-full px-2 py-0.5 text-[11px]" style={{ background: "var(--accent-bg)", color: "var(--accent-ink)" }}>
            {p.label}
          </span>
          <span className="text-[11px] text-faint">{p.indoor ? "rulli" : "fuori"}</span>
        </div>
        {/* What the athlete should know before taking it: a day they fixed that breaks a rule of the method, a type asked in the chat on a bad day. */}
        {p.warnings.length > 0 && (
          <div className="mt-2 rounded-xl px-3 py-2 text-xs" role="alert" style={{ background: "var(--warning-bg)", color: "var(--warning-ink)" }}>
            {p.warnings.map((w) => (
              <div key={w}>{w}</div>
            ))}
          </div>
        )}
        {compact ? (
          <>
            <div className="mt-1 text-[22px] font-semibold leading-tight tracking-tight">{p.workout.name}</div>
            <div className="num mt-0.5 text-sm text-muted">
              {p.mins} min · TSS {p.tss} · {carbsShort(p.mins, p.cls, carbCap)}
            </div>
          </>
        ) : (
          <>
            <div className="mt-1 text-base font-medium">{p.workout.name}</div>
            <div className="num text-xs text-muted">
              {p.mins} min · TSS {p.tss}
            </div>
          </>
        )}
        {p.workout.blocks.length > 0 && (
          <div className="mt-3">
            <WorkoutProfile blocks={p.workout.blocks} height={compact ? 64 : 52} scrub={compact} axis={!compact} />
          </div>
        )}
        {!compact && (
          <>
            <Fuel mins={p.mins} cls={p.cls} cap={carbCap} />
            <ul className="mt-3 space-y-1 text-xs text-muted">
              {p.reasons.map((r) => <li key={r}>{r}</li>)}
              {p.ftpNote && <li>{p.ftpNote}.</li>}
            </ul>
          </>
        )}
        <div className={compact ? "mt-4" : "mt-4 flex flex-wrap items-center gap-2"}>
          <button
            type="button"
            disabled={saving === key || done[key]}
            onClick={() => void schedule(p, today, todayPlanned?.id)}
            className={compact ? "flex min-h-14 w-full items-center justify-center rounded-[18px] text-[17px] font-semibold disabled:opacity-60" : "rounded-xl px-4 py-2 text-sm font-medium disabled:opacity-60"}
            style={compact ? { background: "var(--brand)", color: "var(--on-brand)" } : { background: "var(--accent-bg)", color: "var(--accent-ink)" }}
          >
            {todayPlanned
              ? done[key]
                ? "Sostituito su Intervals"
                : saving === key
                  ? "Sostituisco…"
                  : "Sostituisci su Intervals"
              : done[key]
                ? "Programmato su Intervals"
                : saving === key
                  ? "Programmo…"
                  : "Programma su Intervals"}
          </button>
          {done[key] && <span className={`text-xs text-muted${compact ? " mt-2 block" : ""}`}>Lo trovi nel calendario; da lì puoi aprirlo sul Garmin o sul rullo.</span>}
        </div>
        {compact && (
          <>
            <div className="mt-2 flex justify-center">
              <DetailsToggle open={open} onToggle={() => setOpen((o) => !o)} controls={detailsId} />
            </div>
            <div id={detailsId} hidden={!open}>
              {p.workout.description && (
                <div className="mt-2">
                  <Description text={steps(p.workout.description)} />
                </div>
              )}
              <Fuel mins={p.mins} cls={p.cls} cap={carbCap} />
              <ul className="mt-3 space-y-1 text-xs text-muted">
                {p.reasons.map((r) => <li key={r}>{r}</li>)}
                {p.ftpNote && <li>{p.ftpNote}.</li>}
              </ul>
            </div>
          </>
        )}
        {todayPlanned && (
          <div className="mt-2 text-xs text-muted">
            Prende il posto di «{todayPlanned.name}», che viene tolto dal calendario.{" "}
            <button type="button" onClick={() => setShowOther(false)} className={`text-faint underline${tap}`}>
              Torna a quello in programma
            </button>
          </div>
        )}
        {suggestion.alternatives.length > 0 && (
          <div className="mt-4 border-t pt-3" style={{ borderColor: "var(--border)" }}>
            <div className="text-xs text-faint">Oppure</div>
            <div className="mt-1.5 flex flex-wrap gap-1.5">
              {options.map((o, i) => (
                <button
                  key={o.workout.id}
                  type="button"
                  aria-pressed={i === chosen}
                  onClick={() => setChosen(i)}
                  className={compact ? "min-h-11 rounded-full px-4 text-left text-sm" : "rounded-full px-3 py-1 text-xs"}
                  style={{ background: i === chosen ? "var(--accent-bg)" : "transparent", color: i === chosen ? "var(--accent-ink)" : "var(--foreground)", border: `1px solid ${i === chosen ? "var(--accent-ink)" : "var(--border)"}` }}
                >
                  {o.label}: {o.workout.name}
                </button>
              ))}
            </div>
          </div>
        )}
      </div>
    );
  }

  return (
    <section className="card p-4">
      {header}
      {!compact && <div className="mt-2 text-xs text-muted">
        {weekPlan ? (
          <>
            {PHASE_INFO[weekPlan.phase].label}: {PHASE_INFO[weekPlan.phase].focus}. Settimana {KIND_NAME[weekPlan.kind]}, TSS di riferimento {weekPlan.tssTarget}.{" "}
            <Link href="/stagione" className="underline">
              Piano
            </Link>
          </>
        ) : (
          <Link href="/stagione" className="underline">
            Imposta la stagione: picco di forma e ramp rate →
          </Link>
        )}
      </div>}
      {body}
      {error && (
        <p className="mt-3 text-xs" style={{ color: "var(--critical-ink)" }} role="alert">
          {error}
        </p>
      )}
      {!compact && week.length > 0 && (
        <details className="mt-4 border-t pt-3" style={{ borderColor: "var(--border)" }}>
          <summary className="-my-1.5 cursor-pointer py-1.5 text-xs text-muted">Proposta per la settimana</summary>
          <div className="mt-2 text-[11px] text-faint">Da domani si suppone la prontezza verde: si aggiorna ogni mattina con i dati veri.</div>
          <ul className="mt-2 divide-y" style={{ borderColor: "var(--border)" }}>
            {week.map(({ date, suggestion: s, planned: already }) => {
              return (
                <li key={date} className="flex items-center gap-3 py-2 text-sm" style={{ borderColor: "var(--border)" }}>
                  <span className="w-12 shrink-0 text-xs text-muted">{dayName(date)}</span>
                  <span className="min-w-0 flex-1">
                    {already ? (
                      <span className="text-muted">Già in programma: {already.name}</span>
                    ) : !s || s.kind === "rest" ? (
                      <span className="text-muted">Riposo</span>
                    ) : (
                      <>
                        <span className="font-medium">{s.main.workout.name}</span>
                        <span className="num block text-xs text-muted">
                          {s.main.label} · {s.main.mins} min · TSS {s.main.tss}
                        </span>
                      </>
                    )}
                  </span>
                  {!already && s?.kind === "workout" && date !== today && (
                    <button
                      type="button"
                      disabled={saving === `${date}:${s.main.workout.id}` || done[`${date}:${s.main.workout.id}`]}
                      onClick={() => void schedule(s.main, date)}
                      className="shrink-0 rounded-lg px-2.5 py-1 text-xs disabled:opacity-60"
                      style={{ border: "1px solid var(--border)" }}
                    >
                      {done[`${date}:${s.main.workout.id}`] ? "Fatto" : "Programma"}
                    </button>
                  )}
                </li>
              );
            })}
          </ul>
        </details>
      )}
    </section>
  );
}
