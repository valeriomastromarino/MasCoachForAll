// The Intervals.icu workout text, both ways: what the app writes on the calendar ("Sweet spot 3x / - 12m 88-93%") and
// how it reads back a workout already planned, to change it ("inseriscimi 6 sprint nella Z2 di domani"). Rules of the
// format (verified with the connector since 3 November 2026): one step per line starting with "- ", a repeat is a
// title ending in "Nx" with a blank line before it, a blank line closes the repeat, other lines are section titles.
import type { WorkoutBlock } from "@/lib/workout";
import { ZONE_MID } from "@/lib/workout";
import { BAND, mergeSteps, type Section, type Step, type Target } from "./model";

const pct = (f: number) => String(Math.round(f * 100));

/** 750 → "12m30s", 3600 → "1h", 5400 → "1h30m", 10 → "10s". */
export function durationText(secs: number): string {
  const s = Math.max(1, Math.round(secs));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const r = s % 60;
  return `${h ? `${h}h` : ""}${m ? `${m}m` : ""}${r ? `${r}s` : ""}`;
}

function targetText(st: Step): string {
  const t = st.target;
  const body = st.ramp ? `ramp ${pct(t.lo)}-${pct(t.hi)}%` : pct(t.lo) === pct(t.hi) ? `${pct(t.lo)}%` : `${pct(t.lo)}-${pct(t.hi)}%`;
  return st.rpm ? `${body} ${Math.round(st.rpm)}rpm` : body;
}

/** A title must never look like a repeat ("3x") when the section is ridden once. */
const safeTitle = (title: string) => title.replace(/\b\d+\s*[x×]\s*$/i, "").trim();

export function toIntervalsText(sections: Section[]): string {
  const parts: string[] = [];
  for (const s of sections) {
    const lines = s.steps.filter((st) => st.secs > 0).map((st) => `- ${durationText(st.secs)} ${targetText(st)}`);
    if (!lines.length) continue;
    const title = s.reps > 1 ? `${safeTitle(s.title) || "Ripetute"} ${s.reps}x` : safeTitle(s.title);
    parts.push([title, ...lines].filter(Boolean).join("\n"));
  }
  // A blank line between sections: it opens and closes every repeat, as Intervals.icu needs.
  return parts.join("\n\n");
}

const DUR = /^((?:\d+(?:[.,]\d+)?\s*(?:h|m|s)\s*)+)/i;

function parseDuration(s: string): { secs: number; rest: string } | null {
  const m = s.match(DUR);
  if (!m) return null;
  let secs = 0;
  for (const p of m[1].matchAll(/(\d+(?:[.,]\d+)?)\s*(h|m|s)/gi)) {
    const n = Number(p[1].replace(",", "."));
    secs += n * (p[2].toLowerCase() === "h" ? 3600 : p[2].toLowerCase() === "m" ? 60 : 1);
  }
  return secs > 0 ? { secs: Math.round(secs), rest: s.slice(m[0].length).trim() } : null;
}

function parseTarget(rest: string, ftp: number | null): { target: Target; ramp: boolean; rpm: number | null } | null {
  const r = rest.toLowerCase();
  const rpm = r.match(/(\d{2,3})\s*rpm/);
  const ramp = /\bramp\b/.test(r);
  let m = r.match(/(\d+(?:\.\d+)?)\s*(?:-\s*(\d+(?:\.\d+)?))?\s*%(?!\s*(?:lthr|hr|fc))/);
  if (m) {
    const lo = Number(m[1]) / 100;
    return { target: { lo, hi: m[2] ? Number(m[2]) / 100 : lo }, ramp, rpm: rpm ? Number(rpm[1]) : null };
  }
  m = r.match(/(\d+)\s*(?:-\s*(\d+))?\s*w\b/);
  if (m && ftp) {
    const lo = Number(m[1]) / ftp;
    return { target: { lo, hi: m[2] ? Number(m[2]) / ftp : lo }, ramp, rpm: rpm ? Number(rpm[1]) : null };
  }
  m = r.match(/\bz([1-7])(?:\s*-\s*z?([1-7]))?\b/);
  if (m && !/\bhr\b|lthr/.test(r)) {
    const lo = ZONE_MID[Number(m[1])];
    return { target: { lo, hi: m[2] ? ZONE_MID[Number(m[2])] : lo }, ramp, rpm: rpm ? Number(rpm[1]) : null };
  }
  return null;
}

/**
 * Reads a workout's text back into sections; null when a step line can't be read (heart-rate targets, free text in the
 * steps): then the caller works on the drawn blocks instead.
 */
export function parseIntervalsText(text: string | null | undefined, ftp: number | null): Section[] | null {
  if (!text?.trim()) return null;
  const out: Section[] = [];
  let cur: Section | null = null;
  let title = "";
  let anyStep = false;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) {
      // A blank line closes a repeat.
      if (cur && cur.reps > 1) cur = null;
      continue;
    }
    if (line.startsWith("-")) {
      const d = parseDuration(line.replace(/^-\s*/, ""));
      if (!d) return null;
      const t = parseTarget(d.rest, ftp);
      if (!t) return null;
      if (!cur) {
        cur = { title, reps: 1, steps: [] };
        out.push(cur);
        title = "";
      }
      cur.steps.push({ secs: d.secs, target: t.target, ...(t.ramp ? { ramp: true } : {}), ...(t.rpm ? { rpm: t.rpm } : {}) });
      anyStep = true;
      continue;
    }
    const rep = line.match(/^(.*?)\s*(\d+)\s*[x×]\s*$/i);
    if (rep) {
      cur = { title: rep[1].trim(), reps: Math.max(1, Number(rep[2])), steps: [] };
      out.push(cur);
      continue;
    }
    // Any other line is a title for what follows ("Riscaldamento", "Generated by …").
    title = line.length <= 60 ? line : "";
    cur = null;
  }
  const sections = out.filter((s) => s.steps.length);
  return anyStep && sections.length ? sections : null;
}

/** The drawn blocks as one section: the fallback when the text can't be read. */
export function sectionsFromBlocks(blocks: WorkoutBlock[]): Section[] {
  const steps = blocks.map((b): Step => {
    if (b.pct != null) return { secs: b.secs, target: { lo: b.pct, hi: b.pct } };
    if (b.free && b.secs <= 30) return { secs: b.secs, target: BAND.sprint };
    const f = ZONE_MID[b.zone] ?? 0.5;
    return { secs: b.secs, target: { lo: f, hi: f } };
  });
  return [{ title: "", reps: 1, steps: mergeSteps(steps) }];
}
