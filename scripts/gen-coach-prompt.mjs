// Copies the coach prompt (prompt-coach/MasCoach_prompt.txt, between the INIZIO/FINE lines) into a TS module,
// so the in-app coach (Sonnet) runs with the same rules as the Claude Project. Run after changing the prompt: node scripts/gen-coach-prompt.mjs
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "prompt-coach/MasCoach_prompt.txt";
const OUT = "src/lib/coach/ai/promptBase.generated.ts";
const lines = readFileSync(SRC, "utf8").split(/\r?\n/);
const a = lines.findIndex((l) => l.includes("INIZIO PROMPT"));
const b = lines.findIndex((l) => l.includes("FINE PROMPT"));
if (a < 0 || b < 0) throw new Error("marker INIZIO/FINE PROMPT non trovati");
const text = lines.slice(a + 1, b).join("\n").trim();
writeFileSync(OUT, `// Generated by scripts/gen-coach-prompt.mjs from ${SRC}: do not edit by hand.\nexport const COACH_PROMPT_BASE = ${JSON.stringify(text)};\n`);
console.log(`${OUT}: ${text.length} caratteri`);
